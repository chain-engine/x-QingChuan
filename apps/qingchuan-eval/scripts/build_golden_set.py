def _strip_punct(text: str) -> str:
    return re.sub(r"[\s，。；、：！“”‘’（）《》,.;:!?()\-]", "", text)


def main() -> int:
    # 1) 载入语料并建立“规范化句子”索引（校验 snippet 逐字存在）
    corpus_text: dict[str, str] = {}
    for path in CORPUS_DIR.glob("*.txt"):
        corpus_text[path.name] = path.read_text(encoding="utf-8")

    entries: list[GoldenSetEntry] = []
    seen_ids: set[str] = set()
    for eid, q, ans, cat, diff, gold, note in ENTRIES:
        if eid in seen_ids:
            print(f"重复 id: {eid}", file=sys.stderr)
            return 1
        seen_ids.add(eid)
        gold_refs = []
        for doc, snippet in gold:
            if doc not in corpus_text:
                print(f"{eid}: 语料缺失 {doc}", file=sys.stderr)
                return 1
            if _strip_punct(snippet) not in _strip_punct(corpus_text[doc]):
                print(f"{eid}: snippet 未在 {doc} 中找到（{snippet[:30]}…）", file=sys.stderr)
                return 1
            gold_refs.append({"doc": doc, "snippet": snippet})
        entries.append(
            GoldenSetEntry(
                id=eid,
                question=q,
                reference_answer=ans,
                category=cat,
                difficulty=diff,
                gold=gold_refs,
                note=note,
            )
        )

    save_golden_set(entries, OUT_PATH)

    # 2) 回读校验
    loaded = load_golden_set(OUT_PATH)
    assert len(loaded) == len(entries), "回读条数不一致"
    from collections import Counter

    print(f"golden set 写入: {OUT_PATH}（{len(loaded)} 条）")
    print("分类分布:", dict(Counter(e.category for e in loaded)))
    print("难度分布:", dict(Counter(e.difficulty for e in loaded)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
